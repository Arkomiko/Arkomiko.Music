// Круглые флаги языков для переключателя в шапке: src/assets/flags/<код языка>.svg.
// Источник — набор circle-flags (MIT, лицензия рядом с флагами): у языков, для которых в наборе есть
// свой флаг, взят он; иначе — флаг страны или региона (en — США, pt — Бразилия, wa — Бельгия, cnr — Черногория,
// fur — Фриули). Флаги лужичан, кашубов, силезцев, русинов, ладинов и астурийцев нарисованы в том же стиле.
// Новый язык — положить <код>.svg в src/assets/flags/; без файла в переключателе будет глобус.

// no-inline: флаги — отдельные файлы, а не data:-адреса в HTML (60 флагов раздули бы каждую страницу);
// браузер скачивает их, только когда список языков открыт, и кеширует.
const files = import.meta.glob<string>('/src/assets/flags/*.svg', {
  eager: true,
  query: '?url&no-inline',
  import: 'default',
});

/** Адрес картинки флага или undefined, если флага нет. */
export function flagUrl(lang: string): string | undefined {
  return files[`/src/assets/flags/${lang}.svg`];
}
